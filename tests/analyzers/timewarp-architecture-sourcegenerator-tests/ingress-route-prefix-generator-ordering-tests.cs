#region Purpose
// Exercises IngressRoutePrefixGenerator: deterministic ordering of the emitted prefixes.
#endregion

namespace TimeWarp.Architecture.SourceGenerator.Tests;

using static TimeWarp.Architecture.SourceGenerator.Tests.IngressRoutePrefixGeneratorTestFixture;

public class IngressRoutePrefixGenerator_Ordering_Tests
{
  [System.Runtime.CompilerServices.ModuleInitializer]
  internal static void Register() => RegisterTests<IngressRoutePrefixGenerator_Ordering_Tests>();

  public static Task Should_Emit_The_Same_Ordered_Source_On_A_Repeat_Run()
  {
    const string contracts = """
      using TimeWarp.Architecture;
      using TimeWarp.Architecture.Attributes;

      namespace Test.Web.Features;

      [ApiEndpoint]
      public static partial class Zebra
      {
          [ApiRoute("api/zebra/one", HttpVerb.Get)]
          public sealed partial class Query { }
          public sealed class Response { }
      }

      [ApiEndpoint]
      public static partial class Apple
      {
          [ApiRoute("api/apple/one", HttpVerb.Get)]
          public sealed partial class Query { }
          public sealed class Response { }
      }

      [ApiEndpoint]
      public static partial class AppleAgain
      {
          [ApiRoute("api/Apple/two", HttpVerb.Post)]
          public sealed partial class Command { }
          public sealed class Response { }
      }
      """;

    MetadataReference web = GeneratorTestHarness.CompileContractAssembly(contracts, "web-contracts");
    Dictionary<string, string> options = EnabledForWebContracts();

    string first = GeneratedSource(GeneratorTestHarness.RunIngress(new[] { web }, options));
    string second = GeneratedSource(GeneratorTestHarness.RunIngress(new[] { web }, options));

    const string expected = """
      // <auto-generated/>
      #nullable enable
      using System.Collections.Immutable;

      /// <summary>
      /// Top-level '/api/&lt;segment&gt;' prefixes owned by Web.Server, derived from the hosted
      /// web-contracts [ApiRoute] templates (task 107). The YARP ingress loops over <see cref="All"/>
      /// to declare its Web.Server carve-outs, so the ingress cannot drift from the contracts.
      /// Emitted in the global namespace on purpose (see IngressRoutePrefixGenerator Design region).
      /// </summary>
      public static class WebServerApiRoutePrefixes
      {
        /// <summary>The distinct top-level api prefixes, sorted ordinally.</summary>
        public static readonly ImmutableArray<string> All = ImmutableArray.Create(
          "api/Apple",
          "api/zebra");
      }
      """;

    second.ShouldBe(first);
    // The generator adds the trailing LF that a raw string literal drops before its closing quotes.
    first.ShouldBe(expected + "\n");
    first.ShouldNotContain("\r");

    return Task.CompletedTask;
  }

  public static Task Should_Keep_The_Ordinal_Least_Prefix_Spelling_Regardless_Of_Reference_Order()
  {
    const string lower = """
      using TimeWarp.Architecture;
      using TimeWarp.Architecture.Attributes;

      namespace Test.Web.Features;

      [ApiEndpoint]
      public static partial class ListRoles
      {
          [ApiRoute("api/roles/list", HttpVerb.Get)]
          public sealed partial class Query { }
          public sealed class Response { }
      }
      """;

    const string upper = """
      using TimeWarp.Architecture;
      using TimeWarp.Architecture.Attributes;

      namespace Test.Web.Features;

      [ApiEndpoint]
      public static partial class GetRole
      {
          [ApiRoute("api/Roles/item", HttpVerb.Get)]
          public sealed partial class Query { }
          public sealed class Response { }
      }
      """;

    MetadataReference lowerAssembly = GeneratorTestHarness.CompileContractAssembly(lower, "roles-lower");
    MetadataReference upperAssembly = GeneratorTestHarness.CompileContractAssembly(upper, "roles-upper");
    Dictionary<string, string> options = new()
    {
      ["EnableIngressRouteGeneration"] = "true",
      ["IngressWebContractAssemblies"] = "roles-lower;roles-upper",
      ["IngressReservedPathPrefixes"] = "grpc",
    };

    string lowerFirst = GeneratedSource(GeneratorTestHarness.RunIngress(new[] { lowerAssembly, upperAssembly }, options));
    string upperFirst = GeneratedSource(GeneratorTestHarness.RunIngress(new[] { upperAssembly, lowerAssembly }, options));

    upperFirst.ShouldBe(lowerFirst);
    lowerFirst.IndexOf("\"api/Roles\"", StringComparison.Ordinal).ShouldBeGreaterThan(-1);
    lowerFirst.IndexOf("\"api/roles\"", StringComparison.Ordinal).ShouldBe(-1);

    return Task.CompletedTask;
  }
}

#region Purpose
// Tests for TWA0038: the 500-line threshold, the generated-code and path exemptions, the
// .editorconfig override, and the message text.
#endregion

#region Design
// Sources are built to an exact `wc -l` line count by SourceOfLines, so the boundary cases
// (500 clean, 501 flagged) do not depend on a hand-counted literal. The diagnostic anchors on
// the first token, which SourceOfLines always puts at line 4 (`namespace`, columns 1-10).
#endregion

// ReSharper disable InconsistentNaming
namespace FileLengthAnalyzer_;

using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;
using Microsoft.CodeAnalysis.CSharp.Testing;
using TimeWarp.Architecture.Analyzers;
using TimeWarp.Architecture.Analyzers.Tests;

public class Should_Limit_File_Length
{
  [System.Runtime.CompilerServices.ModuleInitializer]
  internal static void Register() => RegisterTests<Should_Limit_File_Length>();

  private static CSharpAnalyzerTest<FileLengthAnalyzer, RoslynTestVerifier> Test(string path, string source, string? editorConfig = null)
  {
    CSharpAnalyzerTest<FileLengthAnalyzer, RoslynTestVerifier> test = new();
    test.TestState.Sources.Add((path, source));
    if (editorConfig is not null) test.TestState.AnalyzerConfigFiles.Add(("/.editorconfig", editorConfig));
    return test;
  }

  private static DiagnosticResult Flag(string path, string fileName, int lineCount, int maximumLines) =>
    new DiagnosticResult(id: "TWA0038", DiagnosticSeverity.Warning)
      .WithSpan(path, 4, 1, 4, 10)
      .WithArguments(fileName, lineCount, maximumLines);

  // A file of exactly `lineCount` lines (as `wc -l` counts them), ending in a line break.
  private static string SourceOfLines(int lineCount, string header = "")
  {
    var builder = new StringBuilder();
    builder.Append("#region Purpose\n// Widget used to exercise the file-length limit.\n#endregion\n");
    builder.Append("namespace Contracts;\npublic class Widget\n{\n");
    const int fixedLines = 3 + 3 + 1;
    for (int line = 0; line < lineCount - fixedLines; line++) builder.Append("  // filler\n");
    builder.Append("}\n");
    return header + builder;
  }

  public static async Task Given_File_At_Limit_IsClean()
  {
    string source = SourceOfLines(FileLengthAnalyzer.DefaultMaximumLines);
    FileLengthAnalyzer.CountLines(SourceText.From(source)).ShouldBe(500);

    await Test("/src/widget.cs", source).RunAsync();
  }

  public static async Task Given_File_Over_Limit_Is_Flagged_With_Name_And_Count()
  {
    string source = SourceOfLines(501);

    CSharpAnalyzerTest<FileLengthAnalyzer, RoslynTestVerifier> test = Test("/src/widget.cs", source);
    test.ExpectedDiagnostics.Add(Flag("/src/widget.cs", "widget.cs", 501, 500));

    await test.RunAsync();
  }

  public static async Task Given_Over_Limit_Message_Names_File_And_Count()
  {
    string source = SourceOfLines(612);
    SyntaxTree tree = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(source, path: "/src/widget.cs");
    Compilation compilation = Microsoft.CodeAnalysis.CSharp.CSharpCompilation.Create("probe", [tree]);

    ImmutableArray<Diagnostic> diagnostics = await compilation
      .WithAnalyzers([new FileLengthAnalyzer()])
      .GetAnalyzerDiagnosticsAsync();

    diagnostics.Length.ShouldBe(1);
    diagnostics[0].GetMessage(System.Globalization.CultureInfo.InvariantCulture).ShouldBe(
      "File 'widget.cs' has 612 lines, over the 500-line limit; extract a responsibility into its own type");
  }

  public static async Task Given_Auto_Generated_Header_IsClean()
  {
    await Test("/src/widget.cs", SourceOfLines(800, "// <auto-generated/>\n")).RunAsync();
  }

  public static async Task Given_Generated_File_Names_Are_Clean()
  {
    await Test("/src/widget.g.cs", SourceOfLines(800)).RunAsync();
    await Test("/src/Widget.Designer.cs", SourceOfLines(800)).RunAsync();
  }

  public static async Task Given_Generated_Code_EditorConfig_Section_IsClean()
  {
    // EF migrations are marked this way in the repo .editorconfig (platform/postgres/migrations/**).
    const string editorConfig =
      """
      root = true

      [/src/platform/postgres/migrations/**.cs]
      generated_code = true
      """;

    await Test("/src/platform/postgres/migrations/20261102105501_AddAgentScopeGrants.cs", SourceOfLines(800), editorConfig)
      .RunAsync();
  }

  public static async Task Given_Obj_Or_Goldens_Path_IsClean()
  {
    await Test("/src/obj/debug/widget.cs", SourceOfLines(800)).RunAsync();
    await Test("/repo/goldens/ingress/widget.cs", SourceOfLines(800)).RunAsync();
  }

  public static async Task Given_EditorConfig_Max_Lines_Overrides_Default()
  {
    const string editorConfig =
      """
      root = true

      [*.cs]
      dotnet_diagnostic.TWA0038.max_lines = 600
      """;

    await Test("/src/widget.cs", SourceOfLines(600), editorConfig).RunAsync();

    CSharpAnalyzerTest<FileLengthAnalyzer, RoslynTestVerifier> test = Test("/src/widget.cs", SourceOfLines(601), editorConfig);
    test.ExpectedDiagnostics.Add(Flag("/src/widget.cs", "widget.cs", 601, 600));
    await test.RunAsync();
  }

  public static async Task Given_Pragma_Disable_Suppresses()
  {
    await Test("/src/widget.cs", SourceOfLines(800, "#pragma warning disable TWA0038\n")).RunAsync();
  }

  public static async Task Given_Trailing_Line_Break_Is_Not_Counted()
  {
    FileLengthAnalyzer.CountLines(SourceText.From("a\nb\n")).ShouldBe(2);
    FileLengthAnalyzer.CountLines(SourceText.From("a\nb")).ShouldBe(2);
    FileLengthAnalyzer.CountLines(SourceText.From(string.Empty)).ShouldBe(0);
  }
}

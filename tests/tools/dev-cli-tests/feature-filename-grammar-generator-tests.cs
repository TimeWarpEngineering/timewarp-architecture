#region Purpose
// Pins the feature filename grammar generator: emitted .g.cs and .g.props text, the two registry
// rules it refuses, and agreement between the repo's JSON and its committed outputs.
#endregion

namespace FeatureFilenameGrammarGenerator_;

public class Emit_Given_SampleJson
{
  [System.Runtime.CompilerServices.ModuleInitializer]
  internal static void Register() => RegisterTests<Emit_Given_SampleJson>();

  private const string SampleJson = """
    {
      "layers": [ "contracts", "application", "server" ],
      "unroutedLayers": [ "tests" ],
      "functions": { "handler": "application", "endpoint": "server", "api-endpoint": "server" }
    }
    """;

  private static IReadOnlyList<FeatureFilenameGrammarOutput> Generate()
  {
    FeatureFilenameGrammarGenerator.TryGenerate(SampleJson, out IReadOnlyList<FeatureFilenameGrammarOutput> outputs, out string error)
      .ShouldBeTrue(error);
    return outputs;
  }

  public static Task Outputs_Should_BeCsThenOnePropsPerFamily()
  {
    Generate().Select(output => output.RelativePath).ShouldBe(
    [
      "source/analyzers/timewarp-architecture-convention-analyzers/feature-filename-grammar.g.cs",
      "source/container-apps/web/msbuild/feature-filename-grammar.g.props",
      "source/container-apps/api/msbuild/feature-filename-grammar.g.props",
      "source/container-apps/grpc/msbuild/feature-filename-grammar.g.props",
    ]);
    FeatureFilenameGrammarGenerator.OutputRelativePaths.ShouldBe(Generate().Select(output => output.RelativePath));
    return Task.CompletedTask;
  }

  public static Task Cs_Should_ListRoutedAndUnroutedLayersAndLongestFirstFunctions()
  {
    string cs = Generate()[0].Text;

    cs.ShouldStartWith("// <auto-generated />\n");
    cs.ShouldContain("Edit feature-filename-grammar.json and run dev regenerate-generated.");
    cs.ShouldContain("ImmutableHashSet.Create(System.StringComparer.Ordinal, \"contracts\", \"application\", \"server\", \"tests\");");
    cs.ShouldContain(
      "      new KeyValuePair<string, string>(\"api-endpoint\", \"server\"),\n" +
      "      new KeyValuePair<string, string>(\"endpoint\", \"server\"),\n" +
      "      new KeyValuePair<string, string>(\"handler\", \"application\"),\n");
    cs.ShouldContain(
      "      \"api-endpoint\",\n" +
      "      \"endpoint\",\n" +
      "      \"handler\",\n");
    cs.ShouldContain("ImmutableArray.Create(\"web\", \"api\", \"grpc\");");
    cs.ShouldEndWith("}\n");
    cs.ShouldNotContain("\r");
    return Task.CompletedTask;
  }

  public static Task Props_Should_RouteOnlyRoutedLayers()
  {
    string props = Generate()[2].Text;

    props.ShouldContain("Do not edit by hand. Edit feature-filename-grammar.json and run dev regenerate-generated.");
    props.ShouldContain("<FeatureFilenameLayerSuffixRegex>-(application|contracts|server|tests)$</FeatureFilenameLayerSuffixRegex>");
    props.ShouldContain("    <FeatureFilenameGrammarLayer Include=\"server\" Project=\"api-server\" />\n");
    props.ShouldContain("    <FeatureFilenameGrammarLayer Include=\"tests\" />\n");
    props.ShouldContain("    <FeatureFilenameGrammarFunction Include=\"api-endpoint\" Layer=\"server\" />\n");
    props.ShouldContain(
      "  <ItemGroup Condition=\"'$(MSBuildProjectName)' == 'api-contracts'\">\n" +
      "    <Compile Include=\"$(ApiFeatureTreeRoot)/**/*-contracts.cs\"\n" +
      "             Link=\"features\\%(RecursiveDir)%(Filename)%(Extension)\" />\n" +
      "    <Compile Include=\"$(ApiPlatformTreeRoot)/**/*-contracts.cs\"\n" +
      "             Condition=\"'$(ApiPlatformTreeRoot)' != ''\"\n" +
      "             Link=\"platform\\%(RecursiveDir)%(Filename)%(Extension)\" />\n" +
      "  </ItemGroup>\n");
    props.ShouldNotContain("api-tests");
    props.ShouldNotContain("*-tests.cs");
    props.ShouldEndWith("</Project>\n");
    return Task.CompletedTask;
  }
}

public class Validate_Given_
{
  [System.Runtime.CompilerServices.ModuleInitializer]
  internal static void Register() => RegisterTests<Validate_Given_>();

  public static Task UnregisteredLayer_Should_Fail()
  {
    const string json = """{ "layers": [ "server" ], "functions": { "handler": "application" } }""";

    bool generated = FeatureFilenameGrammarGenerator.TryGenerate(json, out IReadOnlyList<FeatureFilenameGrammarOutput> outputs, out string error);

    generated.ShouldBeFalse();
    outputs.ShouldBeEmpty();
    error.ShouldBe("Function 'handler' maps to unregistered layer 'application'.");
    return Task.CompletedTask;
  }

  public static Task FunctionOnUnroutedLayer_Should_Fail()
  {
    const string json = """{ "layers": [ "server" ], "unroutedLayers": [ "tests" ], "functions": { "spec": "tests" } }""";

    FeatureFilenameGrammarGenerator.TryGenerate(json, out _, out string error).ShouldBeFalse();
    error.ShouldBe("Function 'spec' maps to unregistered layer 'tests'.");
    return Task.CompletedTask;
  }

  public static Task NestedLayerSuffix_Should_Fail()
  {
    const string json = """{ "layers": [ "server", "app-server" ], "functions": {} }""";

    bool generated = FeatureFilenameGrammarGenerator.TryGenerate(json, out IReadOnlyList<FeatureFilenameGrammarOutput> outputs, out string error);

    generated.ShouldBeFalse();
    outputs.ShouldBeEmpty();
    error.ShouldBe("Layer suffix '-app-server' nests inside '-server' (dual glob match risk).");
    return Task.CompletedTask;
  }

  public static Task NestedUnroutedSuffix_Should_Fail()
  {
    const string json = """{ "layers": [ "tests" ], "unroutedLayers": [ "unit-tests" ], "functions": {} }""";

    FeatureFilenameGrammarGenerator.TryGenerate(json, out _, out string error).ShouldBeFalse();
    error.ShouldBe("Layer suffix '-unit-tests' nests inside '-tests' (dual glob match risk).");
    return Task.CompletedTask;
  }

  public static Task MissingLayers_Should_Fail()
  {
    FeatureFilenameGrammarGenerator.TryGenerate("""{ "functions": {} }""", out _, out string error).ShouldBeFalse();
    error.ShouldBe("feature-filename-grammar.json needs a \"layers\" array.");
    return Task.CompletedTask;
  }
}

public class Repo_Given_
{
  [System.Runtime.CompilerServices.ModuleInitializer]
  internal static void Register() => RegisterTests<Repo_Given_>();

  public static Task CommittedOutputs_Should_MatchGeneratedText()
  {
    string root = RepoRoot();
    string json = File.ReadAllText(Path.Combine(root, FeatureFilenameGrammarGenerator.JsonRelativePath));

    FeatureFilenameGrammarGenerator.TryGenerate(json, out IReadOnlyList<FeatureFilenameGrammarOutput> outputs, out string error)
      .ShouldBeTrue(error);

    foreach (FeatureFilenameGrammarOutput output in outputs)
    {
      string committed = File.ReadAllText(Path.Combine(root, output.RelativePath)).ReplaceLineEndings("\n");
      committed.ShouldBe(output.Text, $"{output.RelativePath} drifted. Run `dev regenerate-generated` and commit.");
    }

    return Task.CompletedTask;
  }

  private static string RepoRoot()
  {
    DirectoryInfo? directory = new(AppContext.BaseDirectory);
    while (directory is not null && !Path.Exists(Path.Combine(directory.FullName, ".git")))
    {
      directory = directory.Parent;
    }

    return directory.ShouldNotBeNull().FullName;
  }
}

#region Purpose
// Renders a details-copy plan as partial Command.From and Response.Clone source.
#endregion

#region Design
// Helpers take a non-null sequence and return a new List, HashSet, Dictionary, or array. The
// caller decides whether null stays null. ICloneable reference elements and properties are cloned.
// Strings are not. Get-only and init-only storage is assigned through UnsafeAccessor so the
// constructor, including Guard, does not run again.
#endregion

namespace TimeWarp.Foundation.Contracts.Generators;

using System.Text;

internal static class DetailsCopyEmitter
{
  private readonly record struct HelperShape(
    DetailsCollectionKind Kind,
    string ElementDisplay,
    string KeyDisplay,
    string ValueDisplay,
    bool ElementCloneable,
    bool ElementNullable,
    bool KeyCloneable,
    bool KeyNullable,
    bool ValueCloneable,
    bool ValueNullable);

  internal static string Emit(DetailsPlan plan)
  {
    List<DetailsMember> samples = AssignNames(plan);
    StringBuilder builder = new();
    builder.Append("// <auto-generated/>\n#nullable enable\n");
    if (plan.Namespace.Length > 0)
    {
      builder.Append("namespace ").Append(plan.Namespace).Append(";\n\n");
    }

    int indent = 0;
    foreach (string container in plan.Containers)
    {
      Line(builder, indent, "partial class " + container);
      Line(builder, indent, "{");
      indent++;
    }

    string bases = plan.AddCloneable ? " : global::System.ICloneable" : "";
    Line(builder, indent, "partial class " + plan.ClassName + bases);
    Line(builder, indent, "{");
    int body = indent + 1;

    foreach (DetailsFromPart from in plan.Froms)
    {
      EmitFrom(builder, body, plan.ClassName, from);
    }

    if (plan.EmitClone)
    {
      EmitClone(builder, body, plan.ClassName, plan.CloneMembers);
    }

    foreach (DetailsMember member in plan.CloneMembers)
    {
      if (member.AccessorName.Length > 0)
      {
        EmitAccessor(builder, body, member);
      }
    }

    foreach (DetailsMember sample in samples)
    {
      EmitHelper(builder, body, sample);
    }

    Line(builder, indent, "}");
    for (int index = plan.Containers.Count - 1; index >= 0; index--)
    {
      indent--;
      Line(builder, indent, "}");
    }

    return builder.ToString();
  }

  private static List<DetailsMember> AssignNames(DetailsPlan plan)
  {
    Dictionary<HelperShape, string> names = [];
    List<DetailsMember> samples = [];
    int helperIndex = 0;
    int accessorIndex = 0;

    void AssignHelper(DetailsMember member)
    {
      if (member.Collection == DetailsCollectionKind.None)
      {
        return;
      }

      HelperShape shape = new(
        member.Collection,
        member.ElementDisplay,
        member.KeyDisplay,
        member.ValueDisplay,
        member.ElementCloneable,
        member.ElementNullable,
        member.KeyCloneable,
        member.KeyNullable,
        member.ValueCloneable,
        member.ValueNullable);
      if (!names.TryGetValue(shape, out string? name))
      {
        name = "DetailsCopy" + member.Collection + helperIndex;
        helperIndex++;
        names.Add(shape, name);
        samples.Add(member);
      }

      member.HelperName = name;
    }

    void AssignAccessor(DetailsMember member)
    {
      if (member.WriteKind != DetailsWriteKind.UnsafeField && !member.ReadViaField)
      {
        return;
      }

      member.AccessorName = "DetailsCopyField" + accessorIndex;
      accessorIndex++;
    }

    foreach (DetailsFromPart from in plan.Froms)
    {
      foreach (DetailsMember member in from.Members)
      {
        AssignHelper(member);
      }
    }

    foreach (DetailsMember member in plan.CloneMembers)
    {
      AssignHelper(member);
      AssignAccessor(member);
    }

    return samples;
  }

  private static void EmitFrom(StringBuilder builder, int indent, string className, DetailsFromPart from)
  {
    Line(builder, indent, "/// <summary>Copies <paramref name=\"source\"/> into a new command. Collections are copied.</summary>");
    Line(builder, indent, "public static " + className + " From(" + from.InterfaceDisplay + " source)");
    Line(builder, indent, "{");
    Line(builder, indent + 1, "global::System.ArgumentNullException.ThrowIfNull(source);");

    List<DetailsMember> initializers = [];
    List<DetailsMember> later = [];
    foreach (DetailsMember member in from.Members)
    {
      if (member.WriteKind == DetailsWriteKind.Initializer)
      {
        initializers.Add(member);
      }
      else
      {
        later.Add(member);
      }
    }

    if (initializers.Count == 0)
    {
      Line(builder, indent + 1, className + " command = new();");
    }
    else
    {
      Line(builder, indent + 1, className + " command = new()");
      Line(builder, indent + 1, "{");
      for (int index = 0; index < initializers.Count; index++)
      {
        DetailsMember member = initializers[index];
        string suffix = index == initializers.Count - 1 ? "" : ",";
        Line(
          builder,
          indent + 2,
          member.WriteName + " = " + ValueExpression(member, "source." + member.ReadName) + suffix);
      }

      Line(builder, indent + 1, "};");
    }

    if (later.Count > 0)
    {
      Line(builder, indent + 1, from.InterfaceDisplay + " target = command;");
      foreach (DetailsMember member in later)
      {
        Line(
          builder,
          indent + 1,
          "target." + member.WriteName + " = " + ValueExpression(member, "source." + member.ReadName) + ";");
      }
    }

    Line(builder, indent + 1, "CopyBeyondDetails(command, source);");
    Line(builder, indent + 1, "return command;");
    Line(builder, indent, "}");
    builder.AppendLine();
    Line(builder, indent, "static partial void CopyBeyondDetails(" + className + " command, " + from.InterfaceDisplay + " source);");
    builder.AppendLine();
  }

  private static void EmitClone(StringBuilder builder, int indent, string className, List<DetailsMember> members)
  {
    Line(builder, indent, "/// <summary>Memberwise copy that replaces shared collections and cloneable references.</summary>");
    Line(builder, indent, "public object Clone()");
    Line(builder, indent, "{");
    Line(builder, indent + 1, className + " clone = (" + className + ")MemberwiseClone();");
    foreach (DetailsMember member in members)
    {
      string read = ReadExpression(member, "this");
      string value = ValueExpression(member, read);
      string statement = member.WriteKind switch
      {
        DetailsWriteKind.Interface =>
          "((" + member.InterfaceDisplay + ")clone)." + member.WriteName + " = " + value + ";",
        DetailsWriteKind.UnsafeField =>
          member.AccessorName + "(clone) = " + value + ";",
        _ => "clone." + member.WriteName + " = " + value + ";"
      };
      Line(builder, indent + 1, statement);
    }

    Line(builder, indent + 1, "return clone;");
    Line(builder, indent, "}");
    builder.AppendLine();
  }

  private static void EmitAccessor(StringBuilder builder, int indent, DetailsMember member)
  {
    Line(
      builder,
      indent,
      "[global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Field, Name = \""
      + Escape(member.FieldName)
      + "\")]");
    Line(
      builder,
      indent,
      "private static extern ref " + member.TypeDisplay + " " + member.AccessorName + "(" + member.FieldOwnerDisplay + " target);");
    builder.AppendLine();
  }

  private static void EmitHelper(StringBuilder builder, int indent, DetailsMember member)
  {
    if (member.Collection == DetailsCollectionKind.Array)
    {
      string array = member.ElementDisplay + "[]";
      Line(builder, indent, "private static " + array + " " + member.HelperName + "(" + array + " source)");
      Line(builder, indent, "{");
      Line(builder, indent + 1, array + " copy = new " + member.ElementDisplay + "[source.Length];");
      Line(builder, indent + 1, "for (int index = 0; index < source.Length; index++)");
      Line(builder, indent + 1, "{");
      Line(builder, indent + 2, member.ElementDisplay + " item = source[index];");
      Line(builder, indent + 2, "copy[index] = " + ElementValue(member.ElementDisplay, member.ElementCloneable, member.ElementNullable) + ";");
      Line(builder, indent + 1, "}");
      Line(builder, indent + 1, "return copy;");
      Line(builder, indent, "}");
      builder.AppendLine();
      return;
    }

    if (member.Collection == DetailsCollectionKind.Dictionary)
    {
      string pair = "global::System.Collections.Generic.KeyValuePair<" + member.KeyDisplay + ", " + member.ValueDisplay + ">";
      string dictionary = "global::System.Collections.Generic.Dictionary<" + member.KeyDisplay + ", " + member.ValueDisplay + ">";
      Line(builder, indent, "private static " + dictionary + " " + member.HelperName + "(global::System.Collections.Generic.IEnumerable<" + pair + "> source)");
      Line(builder, indent, "{");
      Line(builder, indent + 1, dictionary + " copy = new();");
      Line(builder, indent + 1, "foreach (" + pair + " pair in source)");
      Line(builder, indent + 1, "{");
      Line(builder, indent + 2, member.KeyDisplay + " key = " + Copied("pair.Key", member.KeyDisplay, member.KeyCloneable, member.KeyNullable) + ";");
      Line(builder, indent + 2, member.ValueDisplay + " value = " + Copied("pair.Value", member.ValueDisplay, member.ValueCloneable, member.ValueNullable) + ";");
      Line(builder, indent + 2, "copy.Add(key, value);");
      Line(builder, indent + 1, "}");
      Line(builder, indent + 1, "return copy;");
      Line(builder, indent, "}");
      builder.AppendLine();
      return;
    }

    string concrete = member.Collection == DetailsCollectionKind.HashSet
      ? "global::System.Collections.Generic.HashSet<" + member.ElementDisplay + ">"
      : "global::System.Collections.Generic.List<" + member.ElementDisplay + ">";
    Line(
      builder,
      indent,
      "private static " + concrete + " " + member.HelperName + "(global::System.Collections.Generic.IEnumerable<" + member.ElementDisplay + "> source)");
    Line(builder, indent, "{");
    Line(builder, indent + 1, concrete + " copy = new();");
    Line(builder, indent + 1, "foreach (" + member.ElementDisplay + " item in source)");
    Line(builder, indent + 1, "{");
    Line(builder, indent + 2, "copy.Add(" + ElementValue(member.ElementDisplay, member.ElementCloneable, member.ElementNullable) + ");");
    Line(builder, indent + 1, "}");
    Line(builder, indent + 1, "return copy;");
    Line(builder, indent, "}");
    builder.AppendLine();
  }

  private static string ReadExpression(DetailsMember member, string receiver)
  {
    if (member.ReadViaField)
    {
      return member.AccessorName + "(" + receiver + ")";
    }

    if (member.WriteKind == DetailsWriteKind.Interface)
    {
      return "((" + member.InterfaceDisplay + ")" + receiver + ")." + member.ReadName;
    }

    return receiver + "." + member.ReadName;
  }

  private static string ValueExpression(DetailsMember member, string read)
  {
    if (member.Collection != DetailsCollectionKind.None)
    {
      string copy = member.HelperName + "(" + read + ")";
      string empty = Empty(member);
      return member.Nullable
        ? read + " is null ? null : " + copy
        : read + " is null ? " + empty + " : " + copy;
    }

    if (member.CloneableReference)
    {
      return Copied(read, member.TypeDisplay, cloneable: true, member.Nullable);
    }

    return read;
  }

  private static string Empty(DetailsMember member) => member.Collection switch
  {
    DetailsCollectionKind.Array => "new " + member.ElementDisplay + "[0]",
    DetailsCollectionKind.HashSet => "new global::System.Collections.Generic.HashSet<" + member.ElementDisplay + ">()",
    DetailsCollectionKind.Dictionary =>
      "new global::System.Collections.Generic.Dictionary<" + member.KeyDisplay + ", " + member.ValueDisplay + ">()",
    _ => "new global::System.Collections.Generic.List<" + member.ElementDisplay + ">()"
  };

  private static string ElementValue(string typeDisplay, bool cloneable, bool nullable) =>
    Copied("item", typeDisplay, cloneable, nullable);

  private static string Copied(string read, string typeDisplay, bool cloneable, bool nullable)
  {
    if (!cloneable)
    {
      return read;
    }

    string nonNull = nullable && typeDisplay.EndsWith('?', StringComparison.Ordinal) ? typeDisplay[..^1] : typeDisplay;
    string cloned = "(" + nonNull + ")((global::System.ICloneable)" + read + ").Clone()";
    return nullable ? read + " is null ? null : " + cloned : cloned;
  }

  private static string Escape(string value) => value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);

  private static void Line(StringBuilder builder, int indent, string text)
  {
    builder.Append(' ', indent * 2);
    builder.AppendLine(text);
  }
}

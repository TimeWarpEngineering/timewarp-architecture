#!/usr/bin/env python3
"""Generate FeatureFilenameGrammar.g.cs and feature-filename-grammar.g.props from SSOT JSON."""
from __future__ import annotations

import json
import sys
from pathlib import Path


def layers_nest(layers: list[str]) -> str | None:
  """Return a human message if any registered -{layer} suffix nests inside another."""
  suffixes = [f"-{layer}" for layer in layers]
  for a in suffixes:
    for b in suffixes:
      if a != b and a.endswith(b):
        return f"Layer suffix '{a}' nests inside '{b}' (dual glob match risk)."
  return None


def main() -> int:
  if len(sys.argv) != 4:
    print("Usage: generate-feature-filename-grammar.py <json> <out-cs> <out-props>", file=sys.stderr)
    return 1

  json_path = Path(sys.argv[1])
  out_cs = Path(sys.argv[2])
  out_props = Path(sys.argv[3])

  data = json.loads(json_path.read_text(encoding="utf-8"))
  layers: list[str] = data["layers"]
  functions: dict[str, str] = data["functions"]

  for function, layer in functions.items():
    if layer not in layers:
      print(f"Function '{function}' maps to unregistered layer '{layer}'.", file=sys.stderr)
      return 2

  nesting = layers_nest(layers)
  if nesting:
    print(nesting, file=sys.stderr)
    return 3

  out_cs.parent.mkdir(parents=True, exist_ok=True)
  out_props.parent.mkdir(parents=True, exist_ok=True)

  layer_args = ", ".join(f'"{layer}"' for layer in layers)
  function_entries = "\n".join(
    f'      new KeyValuePair<string, string>("{function}", "{layer}"),'
    for function, layer in sorted(functions.items())
  )
  longest_first = "\n".join(
    f'      "{function}",'
    for function in sorted(functions.keys(), key=lambda f: (-len(f), f))
  )
  # Regex alternation is longest-first so multi-token layer names match correctly if added later.
  layer_alt = "|".join(sorted(layers, key=lambda layer: (-len(layer), layer)))

  cs = f"""// <auto-generated />
// Generated from feature-filename-grammar.json — do not edit. Edit the JSON and rebuild.
#nullable enable
namespace TimeWarp.Architecture.Analyzers;

using System.Collections.Generic;
using System.Collections.Immutable;

/// <summary>SSOT-backed feature filename grammar constants (TWA0015/TWA0016).</summary>
internal static class FeatureFilenameGrammar
{{
  public static readonly ImmutableHashSet<string> Layers =
    ImmutableHashSet.Create(System.StringComparer.Ordinal, {layer_args});

  public static readonly ImmutableDictionary<string, string> FunctionToLayer =
    ImmutableDictionary.CreateRange(System.StringComparer.Ordinal, new[]
    {{
{function_entries}
    }});

  public static readonly ImmutableArray<string> FunctionsLongestFirst =
    ImmutableArray.CreateRange(new[]
    {{
{longest_first}
    }});
}}
"""
  out_cs.write_text(cs, encoding="utf-8")

  layer_items = "\n".join(
    f'    <FeatureFilenameGrammarLayer Include="{layer}" Project="web-{layer}" />'
    for layer in layers
  )
  function_items = "\n".join(
    f'    <FeatureFilenameGrammarFunction Include="{function}" Layer="{layer}" />'
    for function, layer in sorted(functions.items())
  )
  # Hybrid Compile globs generated from the layer list (SSOT — do not hand-list in targets).
  compile_groups = "\n".join(
    f"""  <ItemGroup Condition="'$(MSBuildProjectName)' == 'web-{layer}'">
    <Compile Include="$(WebFeatureTreeRoot)/**/*-{layer}.cs"
             Link="features\\%(RecursiveDir)%(Filename)%(Extension)" />
  </ItemGroup>"""
    for layer in layers
  )
  props = f"""<!--
  AUTO-GENERATED from source/analyzers/timewarp-architecture-convention-analyzers/feature-filename-grammar.json
  Do not edit by hand. Edit the JSON and rebuild the convention-analyzers project (or run the generator).
  Registry edit ⇒ full rebuild (analyzer incremental staleness).
  Nesting of layer suffixes is rejected at generation time (dual-match prevention).
-->
<Project>
  <PropertyGroup>
    <FeatureFilenameLayerSuffixRegex>-({layer_alt})$</FeatureFilenameLayerSuffixRegex>
  </PropertyGroup>
  <ItemGroup>
{layer_items}
{function_items}
  </ItemGroup>
  <!-- Hybrid includes (option 1): require WebFeatureTreeRoot set by feature-membership.targets. -->
{compile_groups}
</Project>
"""
  out_props.write_text(props, encoding="utf-8")
  print(f"Generated {out_cs}")
  print(f"Generated {out_props}")
  return 0


if __name__ == "__main__":
  raise SystemExit(main())

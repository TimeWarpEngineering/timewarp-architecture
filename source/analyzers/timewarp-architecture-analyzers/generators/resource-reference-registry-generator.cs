#region Purpose
// Generates the Ask @ resource-type registry from every [ReferenceableResource] list query contract.
#endregion

#region Design
// Task 345. The registry is derived, never hand-maintained: marking a list query contract is
// what makes it referenceable. Assemblies are the marked hosted-contract assemblies plus this
// compilation (HostedRouteDiscovery, the same rule as the mock-factory registry). Emission is
// gated on the compilation declaring the hand-written ResourceReferenceType (the SPA), and the
// generated list lives in that type's namespace. Each entry calls ResourceReferenceType.Create
// with the prefix, display name, id type name, the [EndpointAuthorize] Policy, and lambdas that
// build the Query (Search set; UserId stamped when the query is an IAuthApiRequest, the mock
// identity signal the SPA's other handlers stamp too), list the Response items, and read the id
// and label. Contracts whose shape is wrong (ReferenceableResourceShape, TWA0033 in contracts)
// are skipped. A repeated prefix keeps the first contract by name; TWA0034 reports it in
// contracts. Entries are sorted by prefix for deterministic output.
#endregion

namespace TimeWarp.Architecture.Analyzers;

using System.Collections.Generic;

/// <summary>Source generator that emits the Ask @ resource-type registry from [ReferenceableResource] contracts.</summary>
[Generator]
public sealed class ResourceReferenceRegistryGenerator : IIncrementalGenerator
{
  private const string HostTypeName = "ResourceReferenceType";

  /// <summary>Registers incremental generator steps for resource-reference registry emission.</summary>
  public void Initialize(IncrementalGeneratorInitializationContext context)
  {
    context.RegisterSourceOutput(context.CompilationProvider, static (spc, compilation) => Execute(spc, compilation));
  }

  private static void Execute(SourceProductionContext context, Compilation compilation)
  {
    INamedTypeSymbol? host = compilation.GetSymbolsWithName(HostTypeName, SymbolFilter.Type)
      .OfType<INamedTypeSymbol>()
      .FirstOrDefault();
    if (host is null) return;

    var shapes = new List<ReferenceableResourceShape>();
    IEnumerable<IAssemblySymbol> assemblies = HostedRouteDiscovery.GetMarkedReferencedAssemblies(compilation)
      .Concat(new[] { compilation.Assembly });

    foreach (IAssemblySymbol assembly in assemblies)
    {
      foreach (INamedTypeSymbol type in HostedRouteDiscovery.GetAllTypes(assembly.GlobalNamespace))
      {
        AttributeData? attribute = ReferenceableResourceShape.FindAttribute(type);
        if (attribute is null) continue;

        var shape = ReferenceableResourceShape.Read(type, attribute, out _);
        if (shape is not null) shapes.Add(shape);
      }
    }

    shapes.Sort(static (a, b) =>
    {
      int byPrefix = string.CompareOrdinal(a.Prefix, b.Prefix);
      return byPrefix != 0 ? byPrefix : string.CompareOrdinal(a.ContractType, b.ContractType);
    });

    string hostType = host.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
    var sb = new StringBuilder();
    sb.Append("// <auto-generated/>\n#nullable enable\n");
    sb.Append("namespace ").Append(host.ContainingNamespace.ToDisplayString()).Append(";\n\n");
    sb.Append("internal static class GeneratedResourceReferenceTypes\n{\n");
    sb.Append("  internal static global::System.Collections.Generic.IReadOnlyList<").Append(hostType).Append("> Create() =>\n");
    sb.Append("  [\n");
    var seen = new HashSet<string>(System.StringComparer.Ordinal);
    foreach (ReferenceableResourceShape shape in shapes)
    {
      if (!seen.Add(shape.Prefix)) continue;

      sb.Append("    ").Append(hostType).Append(".Create<")
        .Append(shape.QueryType).Append(", ").Append(shape.ResponseType).Append(", ").Append(shape.ItemType).Append(">\n");
      sb.Append("    (\n");
      sb.Append("      ").Append(Literal(shape.Prefix)).Append(",\n");
      sb.Append("      ").Append(Literal(shape.DisplayName)).Append(",\n");
      sb.Append("      ").Append(Literal(shape.IdTypeName)).Append(",\n");
      sb.Append("      ").Append(shape.Policy is null ? "null" : Literal(shape.Policy)).Append(",\n");
      sb.Append("      static search => new ").Append(shape.QueryType).Append(" { Search = search");
      if (shape.QuerySetsUserId)
      {
        sb.Append(", UserId = global::System.Guid.NewGuid()");
      }

      sb.Append(" },\n");
      sb.Append("      static response => response.").Append(shape.ItemsProperty).Append(",\n");
      sb.Append("      static item => item.").Append(shape.IdProperty).Append(".ToString(),\n");
      sb.Append("      static item => item.").Append(shape.LabelProperty).Append('\n');
      sb.Append("    ),\n");
    }

    sb.Append("  ];\n}\n");

    context.AddSource("GeneratedResourceReferenceTypes.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
  }

  private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);
}

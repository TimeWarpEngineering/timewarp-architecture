#region Purpose
// Writes the source for one [ContractState] state: per contract an ActionSet (Action and Handler), the typed dispatch
// overload, and the hook declarations.
#endregion

#region Design
// A pure function of ContractStateModel. Every type is fully qualified, so the output does not depend on the host's
// global usings. Per contract:
// - <Contract>ActionSet.Action: [TrackAction] (when TimeWarp.State.Plus is referenced) and IBaseAction; carries the
//   contract request as Request.
// - <Contract>ActionSet.Handler: DefaultApiHandler<Action, TRequest, TResponse> with the four constructor
//   dependencies every hand-written handler takes (plus IConfirmationService for a [Destructive] contract).
//   GetRequest copies the request's settable members into a new request, stamps UserId, then calls the build hook.
//   HandleSuccess calls the success hook. HandleError stays DefaultApiHandler's toast.
// - Hooks, declared on the state so they can write its private members:
//   required (access modifier, CS8795 when the body is missing): private partial void On<C>Loaded(Response) for a
//   Query; private partial void Build<C>Request(TRequest) for a DraftRequests contract; private partial
//   Task<bool> Confirm<C>Async(TRequest, IConfirmationService, CancellationToken) for a [Destructive] request.
//   Optional (partial void, dropped when not written): On<C>Succeeded(Response) for a Command;
//   OnBuilding<C>Request(TRequest) for a contract without a draft build.
// - public Task <C>(TRequest request, CancellationToken? externalCancellationToken = null): builds the Action and sends
//   it the way TimeWarp.State's dispatch methods do. A Query's request defaults to new TRequest(), so a page can write
//   RoleState.GetRoles(). TimeWarp.State may also emit internal <C>(Action, CancellationToken?) from the declaration;
//   the two are overloads on different parameter types, so they never clash.
#endregion

namespace TimeWarp.Architecture.Analyzers;

internal static class ContractStateEmitter
{
  private const string Task = "global::System.Threading.Tasks.Task";
  private const string CancellationToken = "global::System.Threading.CancellationToken";

  public static string Emit(ContractStateModel model)
  {
    var sb = new StringBuilder();
    sb.Append("// <auto-generated/>\n");
    sb.Append("#nullable enable\n");
    sb.Append("#pragma warning disable CS1591\n");
    if (model.Namespace is not null) sb.Append("namespace ").Append(model.Namespace).Append(";\n");
    sb.Append('\n');

    string indent = "";
    foreach (string header in model.TypeHeaders)
    {
      sb.Append(indent).Append(header).Append('\n').Append(indent).Append("{\n");
      indent += "  ";
    }

    foreach (ContractActionModel action in model.Actions)
    {
      EmitActionSet(sb, model, action, indent);
      EmitHooks(sb, action, model, indent);
      EmitDispatch(sb, action, indent);
    }

    for (int depth = model.TypeHeaders.Count - 1; depth >= 0; depth--)
    {
      indent = indent.Substring(0, depth * 2);
      sb.Append(indent).Append("}\n");
    }

    sb.Append("#pragma warning restore CS1591\n");
    return sb.ToString();
  }

  private static void EmitActionSet(StringBuilder sb, ContractStateModel model, ContractActionModel action, string i)
  {
    string request = action.RequestType;
    string state = model.StateType;

    sb.Append(i).Append("/// <summary>Sends the ").Append(action.Name).Append(" contract. Generated from [ContractState].</summary>\n");
    sb.Append(i).Append("public static class ").Append(action.ActionSetName).Append('\n').Append(i).Append("{\n");

    sb.Append(i).Append("  /// <summary>Carries the ").Append(action.Name).Append(" request.</summary>\n");
    if (model.TrackActionType is not null) sb.Append(i).Append("  [").Append(model.TrackActionType).Append("]\n");
    sb.Append(i).Append("  public sealed class Action : ").Append(model.ActionBaseType).Append('\n').Append(i).Append("  {\n");
    sb.Append(i).Append("    public Action(").Append(request).Append(" request)\n");
    sb.Append(i).Append("    {\n");
    sb.Append(i).Append("      global::System.ArgumentNullException.ThrowIfNull(request);\n");
    sb.Append(i).Append("      Request = request;\n");
    sb.Append(i).Append("    }\n\n");
    sb.Append(i).Append("    /// <summary>The request the handler copies and sends.</summary>\n");
    sb.Append(i).Append("    public ").Append(request).Append(" Request { get; }\n");
    sb.Append(i).Append("  }\n\n");

    sb.Append(i).Append("  /// <summary>Sends the request and passes the response to the state's hook.</summary>\n");
    sb.Append(i).Append("  internal sealed class Handler : ").Append(model.HandlerBaseType)
      .Append("<Action, ").Append(request).Append(", ").Append(action.ResponseType).Append(">\n");
    sb.Append(i).Append("  {\n");
    if (action.IsDestructive)
    {
      sb.Append(i).Append("    private readonly ").Append(model.ConfirmationServiceType).Append(" Confirmation;\n\n");
    }

    sb.Append(i).Append("    public Handler\n").Append(i).Append("    (\n");
    sb.Append(i).Append("      ").Append(model.StoreType).Append(" store,\n");
    sb.Append(i).Append("      ").Append(model.ApiServiceType).Append(" apiService,\n");
    sb.Append(i).Append("      global::Microsoft.Extensions.Logging.ILogger<Handler> logger,\n");
    sb.Append(i).Append("      ").Append(model.PublisherType).Append(" publisher");
    if (action.IsDestructive) sb.Append(",\n").Append(i).Append("      ").Append(model.ConfirmationServiceType).Append(" confirmation");
    sb.Append('\n').Append(i).Append("    ) : base(store, apiService, logger, publisher)\n");
    sb.Append(i).Append("    {\n");
    if (action.IsDestructive) sb.Append(i).Append("      Confirmation = confirmation;\n");
    sb.Append(i).Append("    }\n\n");

    if (action.IsDestructive)
    {
      sb.Append(i).Append("    protected override ").Append(Task).Append("<bool> ConfirmAsync(Action action, ").Append(CancellationToken).Append(" cancellationToken) =>\n");
      sb.Append(i).Append("      Store.GetState<").Append(state).Append(">().Confirm").Append(action.Name)
        .Append("Async(action.Request, Confirmation, cancellationToken);\n\n");
    }

    sb.Append(i).Append("    protected override ").Append(Task).Append('<').Append(request).Append("?> GetRequest(Action action, ")
      .Append(CancellationToken).Append(" cancellationToken)\n");
    sb.Append(i).Append("    {\n");
    sb.Append(i).Append("      ").Append(request).Append(" request = new()\n");
    sb.Append(i).Append("      {\n");
    foreach (string member in action.CopiedMembers)
    {
      sb.Append(i).Append("        ").Append(member).Append(" = action.Request.").Append(member).Append(",\n");
    }

    if (action.StampsUserId) sb.Append(i).Append("        UserId = global::System.Guid.NewGuid(),\n");
    sb.Append(i).Append("      };\n");
    sb.Append(i).Append("      Store.GetState<").Append(state).Append(">().")
      .Append(action.IsDraft ? "Build" : "OnBuilding").Append(action.Name).Append("Request(request);\n");
    sb.Append(i).Append("      return ").Append(Task).Append(".FromResult<").Append(request).Append("?>(request);\n");
    sb.Append(i).Append("    }\n\n");

    sb.Append(i).Append("    protected override ").Append(Task).Append(" HandleSuccess(").Append(action.ResponseType)
      .Append(" response, ").Append(CancellationToken).Append(" cancellationToken)\n");
    sb.Append(i).Append("    {\n");
    sb.Append(i).Append("      Store.GetState<").Append(state).Append(">().On").Append(action.Name)
      .Append(action.IsQuery ? "Loaded" : "Succeeded").Append("(response);\n");
    sb.Append(i).Append("      return ").Append(Task).Append(".CompletedTask;\n");
    sb.Append(i).Append("    }\n");
    sb.Append(i).Append("  }\n");
    sb.Append(i).Append("}\n\n");
  }

  private static void EmitHooks(StringBuilder sb, ContractActionModel action, ContractStateModel model, string i)
  {
    string request = action.RequestType;
    if (action.IsQuery)
    {
      sb.Append(i).Append("/// <summary>Required: stores the ").Append(action.Name)
        .Append(" response and seeds any local draft from it. A missing body is CS8795.</summary>\n");
      sb.Append(i).Append("private partial void On").Append(action.Name).Append("Loaded(").Append(action.ResponseType).Append(" response);\n\n");
    }
    else
    {
      sb.Append(i).Append("/// <summary>Optional: runs after ").Append(action.Name).Append(" succeeds.</summary>\n");
      sb.Append(i).Append("partial void On").Append(action.Name).Append("Succeeded(").Append(action.ResponseType).Append(" response);\n\n");
    }

    if (action.IsDraft)
    {
      sb.Append(i).Append("/// <summary>Required: fills the ").Append(action.Name)
        .Append(" request from local draft state before it is sent. A missing body is CS8795.</summary>\n");
      sb.Append(i).Append("private partial void Build").Append(action.Name).Append("Request(").Append(request).Append(" request);\n\n");
    }
    else
    {
      sb.Append(i).Append("/// <summary>Optional: adjusts the copied ").Append(action.Name).Append(" request before it is sent.</summary>\n");
      sb.Append(i).Append("partial void OnBuilding").Append(action.Name).Append("Request(").Append(request).Append(" request);\n\n");
    }

    if (action.IsDestructive)
    {
      sb.Append(i).Append("/// <summary>Required: asks before the [Destructive] ").Append(action.Name)
        .Append(" request is sent. False skips it. A missing body is CS8795.</summary>\n");
      sb.Append(i).Append("private partial ").Append(Task).Append("<bool> Confirm").Append(action.Name).Append("Async(")
        .Append(request).Append(" request, ").Append(model.ConfirmationServiceType).Append(" confirmation, ")
        .Append(CancellationToken).Append(" cancellationToken);\n\n");
    }
  }

  // State's dispatch shape (DispatchMethodEmitter): an optional external token linked with the state's own token,
  // then Sender.Send. Emitted here rather than wrapping State's declared method; see the generator's Design region.
  private static void EmitDispatch(StringBuilder sb, ContractActionModel action, string i)
  {
    string request = action.RequestType;
    sb.Append(i).Append("/// <summary>Dispatches ").Append(action.ActionSetName).Append(".Action with <paramref name=\"request\"/>")
      .Append(action.RequestIsOptional ? " (a new request when null)" : "").Append(".</summary>\n");
    sb.Append(i).Append("public async ").Append(Task).Append(' ').Append(action.Name).Append('(').Append(request)
      .Append(action.RequestIsOptional ? "? request = null" : " request")
      .Append(", ").Append(CancellationToken).Append("? externalCancellationToken = null)\n");
    sb.Append(i).Append("{\n");
    sb.Append(i).Append("  using global::System.Threading.CancellationTokenSource? linkedCts = externalCancellationToken.HasValue\n");
    sb.Append(i).Append("    ? global::System.Threading.CancellationTokenSource.CreateLinkedTokenSource(externalCancellationToken.Value, CancellationToken)\n");
    sb.Append(i).Append("    : null;\n\n");
    sb.Append(i).Append("  await Sender.Send\n").Append(i).Append("  (\n");
    sb.Append(i).Append("    new ").Append(action.ActionSetName).Append(".Action(request")
      .Append(action.RequestIsOptional ? " ?? new " + request + "()" : "").Append("),\n");
    sb.Append(i).Append("    linkedCts?.Token ?? CancellationToken\n");
    sb.Append(i).Append("  );\n");
    sb.Append(i).Append("}\n\n");
  }
}

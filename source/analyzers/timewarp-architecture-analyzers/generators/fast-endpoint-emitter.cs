#region Purpose
// Emitter for FastEndpointSourceGenerator: the ApiEndpointsEmbedded marker sources and one
// BaseFastEndpoint class per valid contract (route, auth, binder, tags, OpenAPI summary).
#endregion

#region Design
// Endpoint summary order (task 472). The first non-empty source wins: XML <summary> on the
// nested Query/Command, then [Operation(Description = ...)] on that request, then XML <summary>
// on the outer [ApiEndpoint] static class. With none of them the summary is empty and no
// s.Summary line is emitted. EndpointDocumentationResolver implements the order (remarks too).
// The same text goes into the generated class's /// comment (XML-escaped) and into the
// Summary(...) string literal (C#-escaped). The resolver joins wrapped lines into one line.
#endregion

namespace TimeWarp.Architecture.Analyzers;

using System.Collections.Generic;
using TimeWarp.Architecture.Analyzers.Models;

/// <summary>Renders FastEndpointSourceGenerator output text from EndpointEmitModel values.</summary>
internal static class FastEndpointEmitter
{
  internal const string MarkerAttributeSource =
    """
    // <auto-generated/>
    #nullable enable
    namespace TimeWarp.Architecture;

    [System.AttributeUsage(System.AttributeTargets.Assembly, Inherited = false)]
    internal sealed class ApiEndpointsEmbeddedAttribute : System.Attribute
    {
    }
    """;

  internal const string MarkerSource =
    """
    // <auto-generated/>
    [assembly: TimeWarp.Architecture.ApiEndpointsEmbedded]
    """;

  internal static string GenerateEndpointClass(EndpointEmitModel metadata)
  {
    // FE Tags() = endpoint-filter metadata only. OpenAPI/Scalar need Description.WithTags.
    string tagArgs = metadata.Tags.Length > 0
      ? string.Join(", ", metadata.Tags.Select(static t => $"\"{t}\""))
      : string.Empty;

    string tagsFilter = metadata.Tags.Length > 0
      ? $"Tags({tagArgs});"
      : "";

    string auth = BuildAuthConfiguration(metadata);

    // FE default RequestBinder TypeInit-fails on DTOs with zero public properties.
    string emptyBinder = metadata.IsEmptyRequest
      ? $"RequestBinder(new EmptyRequestBinder<{metadata.ClassName}.{metadata.RequestTypeName}>());"
      : "";

    // WithTags stays on its own Description call. A Produces(200, "Success") chain binds
    // "Success" as a media type and replaces FastEndpoints' OneOf 200 metadata.
    string summary = BuildOpenApiConfiguration(metadata, tagArgs);

    string requestType = metadata.RequestTypeName;

    return $$"""
             using FastEndpoints;
             using OneOf;
             using System.Threading;
             using System.Threading.Tasks;
             using TimeWarp.Foundation.Features;

             namespace {{metadata.Namespace}};

             /// <summary>
             /// {{EscapeForXmlComment(metadata.Summary)}}
             /// </summary>
             /// <remarks>
             /// {{EscapeForXmlComment(metadata.Description)}}
             /// </remarks>
             public class {{metadata.ClassName}}Endpoint : BaseFastEndpoint<{{metadata.ClassName}}.{{requestType}}, {{metadata.ClassName}}.Response>
             {
               public override void Configure()
               {
                 {{metadata.HttpVerb}}("{{metadata.Route}}");
                 {{auth}}
                 {{emptyBinder}}
                 {{tagsFilter}}
                 {{summary}}
               }
             }
             """;
  }

  /// <summary>
  /// Emits Summary/Description for OpenAPI. Response metadata stays on FastEndpoints' defaults
  /// so a documented request does not replace the OneOf 200 schema. An anonymous reason is
  /// appended to the description even when the request has no XML docs.
  /// </summary>
  private static string BuildOpenApiConfiguration(EndpointEmitModel metadata, string tagArgs)
  {
    string openApiDescription = metadata.Description;
    if (!string.IsNullOrEmpty(metadata.AnonymousReason))
    {
      string note = "Intentionally anonymous. " + metadata.AnonymousReason;
      openApiDescription = string.IsNullOrEmpty(openApiDescription)
        ? note
        : openApiDescription + " " + note;
    }

    bool hasSummary = !string.IsNullOrEmpty(metadata.Summary);
    bool hasDescription = !string.IsNullOrEmpty(openApiDescription);
    string summaryBlock = string.Empty;
    if (hasSummary || hasDescription)
    {
      List<string> lines =
      [
        "            Summary(s =>",
        "            {"
      ];
      if (hasSummary)
      {
        lines.Add($"              s.Summary = \"{EscapeForStringLiteral(metadata.Summary)}\";");
      }

      if (hasDescription)
      {
        lines.Add($"              s.Description = \"{EscapeForStringLiteral(openApiDescription)}\";");
      }

      lines.Add("            });");
      lines.Add(string.Empty);
      summaryBlock = string.Join('\n', lines);
    }

    if (metadata.Tags.Length > 0)
    {
      if (summaryBlock.Length > 0)
      {
        summaryBlock += "\n";
      }

      summaryBlock += $"            Description(d => d.WithTags({tagArgs}));";
    }

    return summaryBlock;
  }

  /// <summary>
  /// Builds FastEndpoints Configure() auth lines from [EndpointAuthorize]/[EndpointAllowAnonymous]
  /// metadata. Task 110 fail-closed default: metadata.AllowAnonymous is true ONLY when
  /// [EndpointAllowAnonymous] was present (see EndpointEmitModel.FromSymbol) — in that case emit
  /// AllowAnonymous(). Otherwise: Policy → Policies(...); Roles → Roles(...);
  /// Schemes → AuthSchemes(...); and if NONE of those were set this method emits NOTHING —
  /// FE requires auth by default when AllowAnonymous() is never called.
  /// </summary>
  private static string BuildAuthConfiguration(EndpointEmitModel metadata)
  {
    if (metadata.AllowAnonymous)
    {
      return "AllowAnonymous();";
    }

    var lines = new List<string>();

    if (!string.IsNullOrEmpty(metadata.AuthenticationSchemes))
    {
      lines.Add($"AuthSchemes({FormatCsvStringArgs(metadata.AuthenticationSchemes)});");
    }

    if (!string.IsNullOrEmpty(metadata.AuthorizationPolicy))
    {
      lines.Add($"Policies(\"{EscapeForStringLiteral(metadata.AuthorizationPolicy)}\");");
    }
    else if (!string.IsNullOrEmpty(metadata.Roles))
    {
      lines.Add($"Roles({FormatCsvStringArgs(metadata.Roles)});");
    }

    return lines.Count > 0
      ? string.Join("\n         ", lines)
      : string.Empty;
  }

  private static string FormatCsvStringArgs(string csv)
  {
    IEnumerable<string> parts = csv
      .Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
      .Select(part => $"\"{EscapeForStringLiteral(part)}\"");
    return string.Join(", ", parts);
  }

  private static string EscapeForStringLiteral(string value)
    => value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal);

  private static string EscapeForXmlComment(string value)
    => value
      .Replace("&", "&amp;", StringComparison.Ordinal)
      .Replace("<", "&lt;", StringComparison.Ordinal)
      .Replace(">", "&gt;", StringComparison.Ordinal);
}
